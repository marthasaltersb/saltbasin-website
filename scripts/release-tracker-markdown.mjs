#!/usr/bin/env node
// Renders a release-tracker snapshot (scripts/release-tracker-sync.mjs --out) as Markdown with the same
// layers as the tracker page: overview → feature → round → bug, joined by in-page links so each summary
// line opens its detail and each detail links back up.
//
//   node scripts/release-tracker-markdown.mjs <snapshot.json> [--out docs/release-log/release-tracker.md]
//
// Labels, statuses, summaries and counts only — never transcript text. Fictional data only (public repo).
import fs from 'node:fs';

const argv = process.argv.slice(2);
const opt = (k) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : null; };
const snap = JSON.parse(fs.readFileSync(argv[0], 'utf8'));
const out = opt('--out');

const ROLE = { build: 'Build', integrate: 'Integrate', validate: 'Validate', triage: 'Triage', scope: 'Scope check', fix: 'Fix', record: 'Record', reconcile: 'Reconcile' };
const STATUS = {
  running: 'Running', passed: 'Passed', failing: 'Failing', queued: 'Queued', between_stages: 'Between stages',
  needs_human: 'Needs a person', needs_business_definition: 'Needs a business decision', open: 'Open', recurred: 'Came back',
  fixing: 'Being fixed', fixed_awaiting_retest: 'Fixed, awaiting re-test', retest_failed: 'Re-test failed', verified: 'Verified fixed',
  done: 'Done', failed: 'Failed (agent stopped)', idle_or_done: 'Idle', done_unreconciled: 'Finished, failures not reconciled',
  seen_in_test: 'Seen in test, awaiting triage', retesting: 'Fixed, being retested now',
  retest_failed_pending_triage: 'Retest failed, being triaged', passed_with_backlog: 'Passed (backlog elsewhere)',
  backlog_pre_existing: 'Backlog: was already broken', reassigned: 'Belongs to another feature', process_note: 'Test or process note',
  stopped: 'Stopped (run replaced)', awaiting_retest: 'Fixed, awaiting retest',
};
const EVENT = { found: 'Found', recurred: 'Came back', fixed: 'Fix applied', not_fixed: 'Not fixed', seen: 'Seen in test', verified: 'Verified fixed' };
const SCOPE = { this_feature: 'This feature', pre_existing: 'Was already broken before this work', other_feature: 'Another feature', process_note: 'Test or process note, not a product bug' };
const BACKLOG = ['backlog_pre_existing', 'reassigned', 'process_note'];
const ORDER = { needs_human: 0, needs_business_definition: 1, recurred: 2, retest_failed: 3, open: 4, fixing: 6, fixed_awaiting_retest: 7, reassigned: 8, backlog_pre_existing: 9, process_note: 10, verified: 11 };

const features = snap.features || []; const bugs = (snap.bugs || []).filter((b) => b.status !== 'seen_in_test'); const agents = snap.agents || [];
const st = (s) => STATUS[s] || (s ? String(s).split(', ').map((r) => ROLE[r] || r).join(' + ') : '—');
const cell = (s) => String(s ?? '—').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');
const anchor = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const fLink = (k) => `[${k}](#feature-${anchor(k)})`;
const bLink = (id) => `[${id}](#bug-${anchor(id)})`;
const commit = (c) => (c ? ` ([${String(c).slice(0, 7)}](${snap.repoUrl || ''}/commit/${c}))` : '');
const k = (n) => (n >= 1e6 ? `${(n / 1e6).toFixed(1)}M` : n >= 1e3 ? `${Math.round(n / 1e3)}k` : String(n || 0));
const sortBugs = (l) => [...l].sort((a, b) => (ORDER[a.status] ?? 5) - (ORDER[b.status] ?? 5) || a.id.localeCompare(b.id));
const ownBugs = (key) => bugs.filter((b) => (b.feature === key && !BACKLOG.includes(b.status)) || (b.status === 'reassigned' && b.scope?.owner === key));
const agentName = (a) => `${ROLE[a.role] || a.role || 'Agent'}${a.round ? ` · round ${a.round}` : ''}`;
const bugTable = (list, showFeature = true) => (list.length
  ? [`| Bug | ${showFeature ? 'Feature | ' : ''}Status | Fix attempts | What fails |`, `|---|${showFeature ? '---|' : ''}---|---|---|`,
    ...sortBugs(list).map((b) => `| ${bLink(b.id)} | ${showFeature ? `${fLink(b.feature)}${b.status === 'reassigned' && b.scope?.owner ? ` → ${fLink(b.scope.owner)}` : ''} | ` : ''}${st(b.status)} | ${b.attempts || 0} / ${snap.maxFixAttemptsPerBug} | ${cell(b.step)} |`)].join('\n')
  : '_None._');

const L = [];
const own = bugs.filter((b) => !['verified', ...BACKLOG].includes(b.status));
const human = bugs.filter((b) => ['needs_human', 'needs_business_definition'].includes(b.status));
const running = agents.filter((a) => a.status === 'running');
L.push('# Release tracker', '',
  `Snapshot of the release loop as of **${snap.syncedAt}**. Generated by \`scripts/release-tracker-markdown.mjs\` from the same snapshot the [live tracker](https://claude.ai/artifact/5pmGUtvSVEVEyaTCp3EVma) shows. Every feature and bug name links to its detail below; each detail links back up.`, '',
  '## Overview', '',
  '| | Count |', '|---|---|',
  `| Features passed | ${features.filter((f) => ['passed', 'passed_with_backlog'].includes(f.status)).length} / ${features.length} |`,
  `| Agents running | ${running.length} |`,
  `| [Open bugs (this work)](#open-bugs-this-work) | ${own.length} |`,
  `| [Backlog: not this work](#backlog-not-this-work) | ${bugs.filter((b) => BACKLOG.includes(b.status)).length} |`,
  `| [Bugs verified fixed](#bugs-verified-fixed) | ${bugs.filter((b) => b.status === 'verified').length} |`,
  `| [Need a person](#need-a-person) | ${human.length} |`,
  `| Tokens out / cache read | ${k(snap.totals?.output)} / ${k(snap.totals?.cacheRead)} |`, '');

L.push('## Features', '', '| Feature | Status | Latest test | Rounds | Its own bugs verified | Backlog |', '|---|---|---|---|---|---|',
  ...features.map((f) => {
    const r = f.lastResult; const ob = ownBugs(f.key);
    return `| ${fLink(f.key)} | ${st(f.status)} | ${r ? `Round ${r.round}: ${r.stepsPassed}/${r.stepsTotal}` : 'Not tested yet'} | ${f.rounds} | ${ob.length ? `${ob.filter((b) => b.status === 'verified').length} of ${ob.length}` : '—'} | ${f.backlog || 0} |`;
  }), '');

L.push('## Agents running', '', running.length
  ? ['| Agent | Feature | Latest step | Last activity |', '|---|---|---|---|', ...running.map((a) => `| ${agentName(a)} | ${a.feature ? fLink(a.feature) : '—'} | ${cell(String(a.activity || '').slice(0, 140))} | ${a.lastActivityAt || '—'} |`)].join('\n')
  : '_No agent is running right now._', '');

L.push('## Open bugs (this work)', '', bugTable(own), '');
L.push('## Need a person', '', bugTable(human), '');
L.push('## Backlog: not this work', '', 'Placed elsewhere by the scope check (already broken, another feature’s, or a test/process note). They stay listed until fixed and verified.', '', bugTable(bugs.filter((b) => BACKLOG.includes(b.status))), '');
L.push('## Bugs verified fixed', '', bugTable(bugs.filter((b) => b.status === 'verified')), '');

L.push('---', '', '# Feature detail', '');
for (const f of features) {
  const fa = agents.filter((a) => a.feature === f.key);
  const rounds = [...new Set(fa.map((a) => a.round).filter((r) => r != null))].sort((a, b) => a - b);
  L.push(`## Feature: ${f.key}`, '', `[↑ Features](#features) · Status: **${st(f.status)}** · ${f.rounds} test round${f.rounds === 1 ? '' : 's'}${f.lastResult ? ` · latest: round ${f.lastResult.round}, ${f.lastResult.stepsPassed}/${f.lastResult.stepsTotal} steps` : ''}`, '');
  if (rounds.length) {
    L.push('**Rounds**', '', '| Round | Stage | Status | Result |', '|---|---|---|---|');
    const STAGE = ['validate', 'triage', 'scope', 'fix', 'reconcile', 'integrate'];
    for (const n of rounds) for (const a of fa.filter((x) => x.round === n).sort((x, y) => STAGE.indexOf(x.role) - STAGE.indexOf(y.role))) L.push(`| ${n} | ${ROLE[a.role] || a.role} | ${st(a.status)} | ${cell(a.summary)} |`);
    L.push('');
  }
  L.push('**Its own bugs**', '', bugTable(ownBugs(f.key), false), '');
  const bl = bugs.filter((b) => b.feature === f.key && BACKLOG.includes(b.status));
  if (bl.length) L.push('**Moved to backlog**', '', bugTable(bl, false), '');
}

L.push('---', '', '# Bug detail', '');
for (const b of sortBugs(bugs)) {
  L.push(`## Bug: ${b.id}`, '', `[↑ ${b.feature}](#feature-${anchor(b.feature)}) · **${st(b.status)}** · fix attempts ${b.attempts || 0} of ${snap.maxFixAttemptsPerBug}${b.carriedOver ? ' · kept from an earlier run' : ''}`, '',
    `- **What fails:** ${cell(b.step)}`,
    `- **Root cause:** ${cell(b.rootCause)}`,
    `- **Class:** ${b.class || '—'}`,
    `- **Files:** ${(b.files || []).map((x) => `\`${x}\``).join(', ') || '—'}`,
    `- **Whose bug:** ${b.scope ? `${SCOPE[b.scope.scope] || b.scope.scope}${b.scope.owner ? ` — ${fLink(b.scope.owner)}` : ''}. ${cell(b.scope.evidence)} (${b.scope.decidedBy})` : 'Not scope-checked yet'}`);
  if (b.question) L.push(`- **Question for you:** ${cell(b.question)}`);
  L.push('', '| Round | Event | Note |', '|---|---|---|', ...(b.history || []).map((h) => `| ${h.round || 'Build'} | ${EVENT[h.event] || h.event} | ${cell(h.note)}${commit(h.commit)} |`), '');
}

const md = `${L.join('\n')}\n`;
if (out) fs.writeFileSync(out, md); else process.stdout.write(md);
