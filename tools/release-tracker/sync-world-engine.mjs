#!/usr/bin/env node
// Keeps the Tracker World engine inlined in tools/release-tracker/index.html identical to its sources:
//   src/lib/crystalGeometry.js                  (crystal recipes: lights, gems, rivers, environment)
//   src/lib/trackerWorld/trackerWorldEngine.js  (the world: districts, labels, data views, highlights, history)
// The artifact page is one file that cannot import, so the sources are wrapped in two IIFEs between the
// "world-engine:begin/end" markers. Never edit that block by hand: edit the sources and run
//   node tools/release-tracker/sync-world-engine.mjs           check (exit 1 if the page differs)
//   node tools/release-tracker/sync-world-engine.mjs --write   regenerate the block
// After --write, also run: node tools/release-tracker/sync-setup-guide.mjs --write
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..', '..');
const pagePath = path.join(here, 'index.html');
const BEGIN = '/* world-engine:begin';
const END = '/* world-engine:end */';

function wrap(name, src, label) {
  const names = [];
  const body = src.replace(/^export (async )?(function|const|let|class) (\w+)/gm, (_, a, kind, n) => { names.push(n); return `${a || ''}${kind} ${n}`; });
  if (/<\/script/i.test(body)) throw new Error(`${label} contains "</script", which cannot be inlined`);
  if (/^import /m.test(body)) throw new Error(`${label} has an import; the inlined engine cannot import`);
  return `const ${name} = (() => {\n${body.replace(/\n+$/, '')}\nreturn { ${names.join(', ')} };\n})();`;
}

export function buildBlock() {
  const geo = fs.readFileSync(path.join(root, 'src/lib/crystalGeometry.js'), 'utf8');
  const eng = fs.readFileSync(path.join(root, 'src/lib/trackerWorld/trackerWorldEngine.js'), 'utf8');
  return `${BEGIN} (generated by tools/release-tracker/sync-world-engine.mjs from src/lib/crystalGeometry.js and src/lib/trackerWorld/trackerWorldEngine.js; do not edit here) */\n${wrap('CrystalGeo', geo, 'crystalGeometry.js')}\n${wrap('TrackerWorldKit', eng, 'trackerWorldEngine.js')}\n${END}`;
}

export function checkOrWrite(write) {
  const page = fs.readFileSync(pagePath, 'utf8');
  const a = page.indexOf(BEGIN); const b = page.indexOf(END);
  if (a < 0 || b < 0) return { ok: false, code: 2, message: 'index.html has no world-engine:begin/end markers' };
  const next = page.slice(0, a) + buildBlock() + page.slice(b + END.length);
  if (next === page) return { ok: true, code: 0, message: 'index.html world engine matches its sources' };
  if (write) { fs.writeFileSync(pagePath, next); return { ok: true, code: 0, message: 'Regenerated the world engine block in index.html' }; }
  return { ok: false, code: 1, message: 'index.html world engine differs from src/lib/trackerWorld and crystalGeometry. Run with --write.' };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = checkOrWrite(process.argv.includes('--write'));
  (r.ok ? console.log : console.error)(r.message);
  process.exit(r.code);
}
